<#
.SYNOPSIS
    WSL2 .wslconfig AI & CUDA Memory Optimizer (#025)
.DESCRIPTION
    Creates or updates %USERPROFILE%\.wslconfig tuned for AI/ML workloads with autoMemoryReclaim=gradual and mirrored networking.
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [switch]$DryRun
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

Write-Output "=== [025] WSL2 .wslconfig AI & CUDA Memory Optimizer ==="
$os = Get-CimInstance -ClassName Win32_OperatingSystem
$totalRamGB = [math]::Round($os.TotalVisibleMemorySize / 1MB, 0)
$wslRamGB = [math]::Max(8, [math]::Floor($totalRamGB * 0.75))

$wslConfigPath = Join-Path $env:USERPROFILE ".wslconfig"
$content = @"
# Generated by WinPulse Studio (#025 WSL2 AI & CUDA Optimizer)
[wsl2]
memory=${wslRamGB}GB
swap=8GB
localhostForwarding=true
nestedVirtualization=true
networkingMode=mirrored
dnsTunneling=true
autoProxy=true

[experimental]
autoMemoryReclaim=gradual
sparseVhd=true
"@

Write-Output ("Host RAM: {0} GB -> Allocating {1} GB max to WSL2 with gradual autoMemoryReclaim." -f $totalRamGB, $wslRamGB)
if ($DryRun -or -not $PSCmdlet.ShouldProcess($wslConfigPath, "Write optimized .wslconfig")) {
    Write-Output "[DRY-RUN] Would write the following to ${wslConfigPath}:`n$content"
    return
}

if (Test-Path $wslConfigPath) {
    Copy-Item -Path $wslConfigPath -Destination "$wslConfigPath.bak" -Force
    Write-Output "Backed up existing .wslconfig to $wslConfigPath.bak"
}
Set-Content -Path $wslConfigPath -Value $content -Encoding UTF8
Write-Output "Wrote optimized AI .wslconfig to $wslConfigPath"
